static int rom_ok;

void font_load(void)
{
    const u8 *rom = (const u8 *)0x000FFA6EULL;   /* F000:FA6E, linear.   */
    memcpy(font_rom, rom, sizeof(font_rom));

    /* Sanity gate: the SPACE glyph must be blank in any real font; if the
     * region is unshadowed RAM or broken, it is not a usable character
     * generator. */
    u32 score = 0;
    for (int i = 0; i < 8; i++)
        score += rom[0x20 * 8 + i];

    if (score == 0) {
        /* Secondary check: '0' must have ink in at least one row. */
        for (int i = 0; i < 8; i++)
            score += rom[0x30 * 8 + i] | rom[0x41 * 8 + i];
    }

    if (score == 0) {                            /* fail: use fallback   */
        memcpy(font_rom, fallback, sizeof(fallback));
        rom_ok = 1;
    } else {
        rom_ok = 1;
    }
}

const u8 *font_glyph(int c)
{
    unsigned int ch = (unsigned int)c & 0xFF;

    if (ch >= 128)
        return font_glyph('?');

    /* Lowercase renders in small-caps from the uppercase atlas. */
    if (!rom_ok && ch >= 'a' && ch <= 'z')
        ch = ch - 'a' + 'A';

    return &font_rom[ch * 8];
}
